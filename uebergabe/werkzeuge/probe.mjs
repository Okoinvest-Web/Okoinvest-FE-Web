import { chromium } from "playwright";
const [url, reduced] = process.argv.slice(2);
const browser = await chromium.launch();
const ctx = await browser.newContext({ viewport: { width: 1440, height: 900 }, reducedMotion: reduced ? "reduce" : "no-preference" });
await ctx.addInitScript(() => { try { localStorage.setItem("cookie-consent", "necessary"); } catch {} });
const page = await ctx.newPage();
const fehler = [];
page.on("pageerror", (e) => fehler.push(String(e)));
page.on("console", (m) => m.type() === "error" && fehler.push(m.text().slice(0, 300)));
await page.goto(url, { waitUntil: "commit", timeout: 180000 });
await page.waitForSelector(".ov-te-wort");
const op = () => page.evaluate(() => [...document.querySelectorAll("h1 .ov-te-wort")].map((w) => (+getComputedStyle(w).opacity).toFixed(2)).join(" "));
for (const t of [0, 100, 250, 500, 900]) { await page.waitForTimeout(t ? 100 : 0); console.log("h1 Wörter", await op()); }
await page.waitForLoadState("load"); await page.waitForTimeout(1500);
const b = await page.locator("#magnet").boundingBox();
await page.mouse.move(b.x + b.width - 30, b.y + b.height / 2); await page.mouse.move(b.x + b.width - 20, b.y + 10, { steps: 3 }); await page.waitForTimeout(300);
console.log("magnet", await page.evaluate(() => { const e = document.querySelector("#magnet"); return e.className.includes("ov-magnet") + " " + getComputedStyle(e).transform + " " + e.style.cssText; }));
await page.mouse.move(5, 600); await page.waitForTimeout(600);
console.log("magnet zurück", await page.evaluate(() => getComputedStyle(document.querySelector("#magnet")).transform));
// Scroll zur Überschrift
await page.evaluate(() => document.querySelector("#te-scroll").scrollIntoView({ block: "end" }));
console.log("te-scroll sofort", await page.evaluate(() => [...document.querySelectorAll("#te-scroll .ov-te-wort")].map((w) => (+getComputedStyle(w).opacity).toFixed(2)).join(" ")));
await page.waitForTimeout(300);
console.log("zahl 300ms", await page.evaluate(() => document.querySelector("#zahl").innerText));
await page.waitForTimeout(1500);
console.log("te-scroll 1.8s", await page.evaluate(() => [...document.querySelectorAll("#te-scroll .ov-te-wort")].map((w) => (+getComputedStyle(w).opacity).toFixed(2)).join(" ")));
console.log("zahl Ende", await page.evaluate(() => document.querySelector("#zahl").innerText));
await page.evaluate(() => document.querySelector("#pfad").scrollIntoView({ block: "center" }));
await page.waitForTimeout(400);
console.log("pfad 400ms", await page.evaluate(() => [...document.querySelectorAll("#pfad path")].map((p) => getComputedStyle(p).strokeDashoffset).join(" ")));
await page.waitForTimeout(1500);
console.log("pfad Ende", await page.evaluate(() => [...document.querySelectorAll("#pfad path")].map((p) => getComputedStyle(p).strokeDashoffset).join(" ")));
await page.evaluate(() => document.querySelector("#spot").scrollIntoView({ block: "center" }));
await page.waitForTimeout(900);
const s = await page.locator("#spot").boundingBox();
await page.mouse.move(s.x + 40, s.y + 40); await page.mouse.move(s.x + 60, s.y + 50, { steps: 3 }); await page.waitForTimeout(400);
console.log("spot", await page.evaluate(() => { const e = document.querySelector("#spot"); const l = e.querySelector(".ov-spot-licht"); return e.className + " | " + e.style.cssText + " | op " + getComputedStyle(l, "::before").opacity; }));
await page.screenshot({ path: process.env.D + "/spot.png", clip: { x: s.x - 20, y: s.y - 20, width: 1300, height: s.height + 40 } });
const k = await page.locator("#kipp").boundingBox();
await page.mouse.move(k.x + 10, k.y + 10); await page.mouse.move(k.x + 12, k.y + 12, { steps: 2 }); await page.waitForTimeout(400);
console.log("kipp", await page.evaluate(() => getComputedStyle(document.querySelector("#kipp")).transform));
await page.screenshot({ path: process.env.D + "/kipp.png", clip: { x: s.x - 20, y: s.y - 20, width: 1300, height: s.height + 40 } });
await page.evaluate(() => document.querySelector("#para").scrollIntoView({ block: "center" }));
await page.waitForTimeout(300);
console.log("parallax", await page.evaluate(() => getComputedStyle(document.querySelector("#para > div")).transform));
console.log("fortschritt", await page.evaluate(() => { const e = document.querySelector(".ov-scroll-fortschritt"); return e.hasAttribute("data-css") + " " + getComputedStyle(e).transform; }));
console.log("Fehler", JSON.stringify(fehler));
await browser.close();
